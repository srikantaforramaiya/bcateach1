# Loop from 0 up to (but not including) 5
for i in range(5):
    print(i)
	
	
# Loop from 2 up to (but not including) 6
for i in range(2, 6):
    print(i)
	

# Loop from 1 up to (but not including) 10, incrementing by 2 (odd numbers)
for i in range(1, 10, 2):
    print(i)
	
	
for i in range(5, 0, -1):
    print(i)